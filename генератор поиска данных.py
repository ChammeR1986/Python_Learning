# Метод numbers.count(x) заставляет компьютер каждый раз заново перебирать весь список. 
# Если в списке 10 000 элементов, программа сделает 100 000 000 операций.
# Чтобы этого избежать, используют инструмент Counter из встроенного модуля collections. 
# Он считает все элементы за один проход:

from collections import Counter

numbers = [2, 2, 2, 7, 23, 1, 44, 44, 3, 2, 10, 7, 4, 11]

# 1. Создаем словарь частот: {2: 4, 7: 2, 23: 1, ...}
counts = Counter(numbers)

# 2. Быстрый генератор (мгновенно берёт готовое количество из словаря)
result = [x for x in numbers if counts[x] == 1]

print(result)  # [23, 1, 3, 10, 4, 11]